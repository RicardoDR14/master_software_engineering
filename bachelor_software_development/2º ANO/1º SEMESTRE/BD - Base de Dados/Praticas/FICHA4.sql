--ex6
SELECT DISTINCT LIVROS.TITULO, TO_CHAR(LIVROS.DATA_EDICAO, 'DD-MM-YYYY') AS "DATA"
FROM LIVROS, VENDAS, CLIENTES
WHERE (LIVROS.CODIGO_LIVRO = VENDAS.CODIGO_LIVRO) AND (VENDAS.CODIGO_CLIENTE = CLIENTES.CODIGO_CLIENTE) AND CLIENTES.MORADA LIKE '%Lisboa,%' AND (TO_DATE('15-01-2014', 'DD-MM-YYYY') <= VENDAS.DATA_VENDA AND TO_DATE('18-02-2014', 'DD-MM-YYYY') >= VENDAS.DATA_VENDA) 
ORDER BY TO_CHAR(LIVROS.DATA_EDICAO, 'DD-MM-YYYY'), LIVROS.TITULO ;
EXEC SQLCHECK('FDKWDJZFBNMKJXK');

--ex7
SELECT LIVROS.TITULO, TO_CHAR(LIVROS.DATA_EDICAO, 'YYYY-MM') AS "ANO_MES"
FROM LIVROS,VENDAS
WHERE (LIVROS.CODIGO_LIVRO = VENDAS.CODIGO_LIVRO) AND LIVROS.GENERO = 'Informática' AND TO_CHAR(LIVROS.DATA_EDICAO,'MM-YYYY') = TO_CHAR(VENDAS.DATA_VENDA,'MM-YYYY')
ORDER BY TO_CHAR(LIVROS.DATA_EDICAO, 'YYYY-MM');
EXEC SQLCHECK('FDOVPNBGJYYXKBW');

