SELECT NOME
FROM AUTORES
WHERE NOME NOT IN (
    SELECT NOME
    FROM AUTORES AU, LIVROS L
    WHERE AU.CODIGO_AUTOR = L.CODIGO_AUTOR
)
OR NOME IN (
    SELECT NOME
    FROM AUTORES AU, LIVROS L
    WHERE AU.CODIGO_AUTOR = L.CODIGO_AUTOR
    AND TO_CHAR(DATA_EDICAO, 'YYYY') = '2023'
)
ORDER BY NOME DESC;
EXEC SQLCHECK('FDBJQVPLQMMGPLE');